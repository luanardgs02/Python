numero= 3.14159
# exibir todas as casas decimais
print ('Exibir todas as casas decimais:',numero)

# exibir duas casas decimais
print(f'Exibir duas casas decimais: {numero:.2f}')

# exibir de outra forma duas casas decimais - round= arredondamento
numero_arredondado = round(numero,2)
print('Exibir de outra forma duas casas decimais: ',numero_arredondado)